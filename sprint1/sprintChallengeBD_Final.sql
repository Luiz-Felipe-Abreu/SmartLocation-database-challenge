-- Criar tabela Pátio
CREATE TABLE patio (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    endereco VARCHAR2(255) NOT NULL,
    capacidade NUMBER NOT NULL
);

-- Criar tabela Moto
CREATE TABLE moto (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR2(10) NOT NULL UNIQUE,
    modelo VARCHAR2(50) NOT NULL,
    status VARCHAR2(20) CHECK (status IN ('DISPONIVEL', 'EM_USO', 'MANUTENCAO', 'INATIVA')),
    patio_id NUMBER,
    ultima_atualizacao TIMESTAMP,
    FOREIGN KEY (patio_id) REFERENCES patio(id)
);

-- Criar tabela Posicao
CREATE TABLE posicao (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moto_id NUMBER,
    latitude NUMBER NOT NULL,
    longitude NUMBER NOT NULL,
    timestamp TIMESTAMP,
    FOREIGN KEY (moto_id) REFERENCES moto(id)
);

-- Criar tabela Sensor
CREATE TABLE sensor (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moto_id NUMBER UNIQUE,
    ligado NUMBER(1),
    nivel_bateria NUMBER,
    nivel_combustivel NUMBER,
    ultima_atualizacao TIMESTAMP,
    FOREIGN KEY (moto_id) REFERENCES moto(id)
);

CREATE TABLE manutencao (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moto_id NUMBER NOT NULL,
    descricao VARCHAR2(255),
    custo NUMBER(10,2),
    data_manutencao DATE,
    FOREIGN KEY (moto_id) REFERENCES moto(id)
);

CREATE TABLE usuario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    tipo_usuario VARCHAR2(20) CHECK (tipo_usuario IN ('ADMIN', 'OPERADOR', 'TÉCNICO'))
);


