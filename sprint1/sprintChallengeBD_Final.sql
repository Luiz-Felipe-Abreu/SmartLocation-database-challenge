-- Bloco de anônimos PL/SQL 
-- Consulta 1
SET SERVEROUTPUT ON;
BEGIN
  FOR registro_patio IN (
    SELECT patio_info.nome AS nome_patio, COUNT(moto_data.id) AS total_motos
    FROM patio patio_info
    LEFT JOIN moto moto_data ON moto_data.patio_id = patio_info.id
    GROUP BY patio_info.nome
    ORDER BY total_motos DESC
  ) LOOP
    DBMS_OUTPUT.PUT_LINE('Pátio: ' || registro_patio.nome_patio || ' - Total de Motos: ' || registro_patio.total_motos);
  END LOOP;
END;

-- Consulta 2
SET SERVEROUTPUT ON;
BEGIN
  FOR combustivel_patio IN (
    SELECT patio_info.nome AS nome_patio, ROUND(AVG(sensor_info.nivel_combustivel), 2) AS media_combustivel
    FROM patio patio_info
    JOIN moto moto_data ON moto_data.patio_id = patio_info.id
    JOIN sensor sensor_info ON sensor_info.moto_id = moto_data.id
    GROUP BY patio_info.nome
    ORDER BY media_combustivel DESC
  ) LOOP
    DBMS_OUTPUT.PUT_LINE('Pátio: ' || combustivel_patio.nome_patio || ' - Média de Combustível: ' || combustivel_patio.media_combustivel || '%');
  END LOOP;
END;

-- Consulta 3
SET SERVEROUTPUT ON;
BEGIN
  FOR status_registro IN (
    SELECT moto_data.status AS status_moto, COUNT(*) AS quantidade
    FROM moto moto_data
    GROUP BY moto_data.status
    ORDER BY quantidade DESC
  ) LOOP
    DBMS_OUTPUT.PUT_LINE('Status: ' || status_registro.status_moto || ' - Quantidade de Motos: ' || status_registro.quantidade);
  END LOOP;
END;


-- Linha anterior, atual, proxima
SET SERVEROUTPUT ON;
DECLARE
  TYPE tipo_moto IS TABLE OF moto.placa%TYPE INDEX BY PLS_INTEGER;
  vetor_motos tipo_moto;
  total_motos NUMBER;
BEGIN
  -- Buscar todas as placas ordenadas
  SELECT placa
  BULK COLLECT INTO vetor_motos
  FROM moto
  ORDER BY id;

  -- Descobrir o total de motos coletadas
  total_motos := vetor_motos.COUNT;

  -- Percorrer o vetor
  FOR i IN 1..total_motos LOOP
    -- Mostrar a placa anterior
    IF i = 1 THEN
      DBMS_OUTPUT.PUT_LINE('Anterior: Vazio');
    ELSE
      DBMS_OUTPUT.PUT_LINE('Anterior: ' || vetor_motos(i - 1));
    END IF;

    -- Mostrar a placa atual
    DBMS_OUTPUT.PUT_LINE('Atual: ' || vetor_motos(i));

    -- Mostrar a placa próxima
    IF i = total_motos THEN
      DBMS_OUTPUT.PUT_LINE('Próxima: Vazio');
    ELSE
      DBMS_OUTPUT.PUT_LINE('Próxima: ' || vetor_motos(i + 1));
    END IF;

    DBMS_OUTPUT.PUT_LINE('---------------------------');
  END LOOP;
END;


-- Total de aluguel por clientes
SET SERVEROUTPUT ON;
BEGIN
   FOR r IN (
      SELECT m.placa AS placa_moto,
             COUNT(mt.id) AS total_manutencoes
      FROM moto m
      JOIN manutencao mt ON m.id = mt.moto_id
      GROUP BY m.placa
      ORDER BY total_manutencoes DESC
   ) LOOP
      DBMS_OUTPUT.PUT_LINE('Placa: ' || r.placa_moto || ' - Total de Manutenções: ' || r.total_manutencoes);
   END LOOP;
END;

-- Media do combustivel por media das motos
SET SERVEROUTPUT ON;
BEGIN
   FOR r IN (
      SELECT m.placa,
             m.status,
             ROUND(s.nivel_combustivel, 2) AS media_combustivel
      FROM moto m
      JOIN sensor s ON m.id = s.moto_id
      ORDER BY m.status, s.nivel_combustivel DESC
   ) LOOP
      DBMS_OUTPUT.PUT_LINE('Status moto ' || r.placa || ': ' || r.status || ' - Nível de Combustível: ' || r.media_combustivel);
   END LOOP;
END;

-- Quantidade de motos no patio
SET SERVEROUTPUT ON;
BEGIN
   FOR r IN (
      SELECT p.nome AS nome_patio,
             COUNT(m.id) AS total_motos
      FROM patio p
      JOIN moto m ON p.id = m.patio_id
      GROUP BY p.nome
      ORDER BY total_motos DESC
   ) LOOP
      DBMS_OUTPUT.PUT_LINE('Pátio: ' || r.nome_patio || ' - Total de Motos: ' || r.total_motos);
   END LOOP;
END;


